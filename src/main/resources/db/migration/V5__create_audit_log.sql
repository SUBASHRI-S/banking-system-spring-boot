-- Security and money-movement events (who did what, when, with what result).
-- Append-only: the trigger below rejects UPDATE and DELETE, so history cannot be rewritten
-- through the application or by a casual SQL statement.
CREATE TABLE audit_log (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type    VARCHAR(30)  NOT NULL,
    outcome       VARCHAR(10)  NOT NULL,
    actor_user_id BIGINT,
    target        VARCHAR(255),
    detail        VARCHAR(255),
    request_id    VARCHAR(64),
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_audit_outcome CHECK (outcome IN ('SUCCESS', 'FAILURE'))
);

CREATE INDEX idx_audit_created ON audit_log (created_at DESC);
CREATE INDEX idx_audit_type_created ON audit_log (event_type, created_at DESC);
CREATE INDEX idx_audit_actor ON audit_log (actor_user_id);

CREATE FUNCTION audit_log_append_only() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'audit_log is append-only';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_audit_log_append_only
    BEFORE UPDATE OR DELETE ON audit_log
    FOR EACH ROW EXECUTE FUNCTION audit_log_append_only();
