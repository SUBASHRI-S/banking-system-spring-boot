CREATE TABLE transfers (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    from_account_id BIGINT        NOT NULL REFERENCES accounts (id),
    to_account_id   BIGINT        NOT NULL REFERENCES accounts (id),
    amount          NUMERIC(19,2) NOT NULL,
    status          VARCHAR(10)   NOT NULL DEFAULT 'COMPLETED',
    description     VARCHAR(140),
    idempotency_key VARCHAR(100),
    created_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT ck_transfers_amount_positive CHECK (amount > 0),
    CONSTRAINT ck_transfers_different_accounts CHECK (from_account_id <> to_account_id),
    CONSTRAINT ck_transfers_status CHECK (status IN ('COMPLETED'))
);

-- advanced feature BANK-FR-11: NULL keys never collide, so plain transfers are unaffected
CREATE UNIQUE INDEX uq_transfers_idempotency ON transfers (from_account_id, idempotency_key);
-- used by the daily limit check (BANK-FR-12)
CREATE INDEX idx_transfers_from_created ON transfers (from_account_id, created_at DESC);
