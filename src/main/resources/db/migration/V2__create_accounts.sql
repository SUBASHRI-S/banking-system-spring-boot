CREATE TABLE accounts (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_number VARCHAR(12)   NOT NULL,
    user_id        BIGINT        NOT NULL REFERENCES users (id),
    type           VARCHAR(10)   NOT NULL,
    balance        NUMERIC(19,2) NOT NULL DEFAULT 0,
    status         VARCHAR(10)   NOT NULL DEFAULT 'ACTIVE',
    created_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT uq_accounts_number UNIQUE (account_number),
    CONSTRAINT ck_accounts_number CHECK (account_number ~ '^[0-9]{12}$'),
    CONSTRAINT ck_accounts_type CHECK (type IN ('SAVINGS', 'CURRENT')),
    CONSTRAINT ck_accounts_status CHECK (status IN ('ACTIVE', 'FROZEN', 'CLOSED')),
    -- last safety net: even a buggy service cannot make a balance negative
    CONSTRAINT ck_accounts_balance_non_negative CHECK (balance >= 0)
);

CREATE INDEX idx_accounts_user_id ON accounts (user_id);
